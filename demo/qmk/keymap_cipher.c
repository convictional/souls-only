// Cipher logic for the Souls Keys demo, to be merged into the Keychron V1 Max
// keymap. This file is NOT a full keymap on its own. See demo/BUILD.md.
//
// Behaviour:
//   * Right Ctrl toggles cipher mode on/off (no visual indicator in v1).
//   * In cipher mode, a bare lowercase letter key emits a RANDOM left code then
//     a RANDOM right code for that letter (from cipher_table.h). The Souls Keys
//     font ligates each 2-char code into a half-glyph; the two halves tile into
//     the readable letter, and the REVL axis can scatter/reveal it.
//   * Because the codes are chosen randomly per keypress (homophones), the same
//     letter produces different bytes each time, so the raw stream resists
//     frequency analysis while still rendering correctly.
//   * Any letter pressed with Ctrl/Alt/GUI/Shift passes through unchanged, so
//     shortcuts and capitals keep working. Cipher mode off = normal keyboard.

#include QMK_KEYBOARD_H
#include "cipher_table.h"   // generated by tools/make_qmk_table.py

static bool cipher_on = false;
static bool rng_seeded = false;

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    // Toggle key: Right Ctrl. Swallow both edges so it never acts as Ctrl.
    if (keycode == KC_RCTL) {
        if (record->event.pressed) {
            cipher_on = !cipher_on;
        }
        return false;
    }

    if (!cipher_on || !record->event.pressed) {
        return true;
    }

    if (keycode >= KC_A && keycode <= KC_Z) {
        uint8_t mods = get_mods() | get_weak_mods();
        if (mods == 0) {
            if (!rng_seeded) {        // cheap entropy from the timer
                srand(timer_read32());
                rng_seeded = true;
            }
            uint8_t i = keycode - KC_A;
            send_string(kb_left[i][rand() % KB_HOMOPHONES]);
            send_string(kb_right[i][rand() % KB_HOMOPHONES]);
            return false;  // suppress the original letter
        }
    }

    return true;
}
